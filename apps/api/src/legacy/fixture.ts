/** Test-only Laravel APP_KEY (32 bytes of 0x05) and a `Crypt::encryptString` twin. */
export const FIXTURE_LEGACY_KEY = `base64:${Buffer.alloc(32, 5).toString('base64')}`;

export function laravelEncrypt(plain: string, appKey = FIXTURE_LEGACY_KEY): string {
  const key = Buffer.from(appKey.slice(7), 'base64');
  const iv = randomBytes(16);
  const cipher = createCipheriv('aes-256-cbc', key, iv);
  const value = Buffer.concat([cipher.update(plain, 'utf8'), cipher.final()]).toString('base64');
  const ivB64 = iv.toString('base64');
  const mac = createHmac('sha256', key)
    .update(ivB64 + value)
    .digest('hex');
  return Buffer.from(JSON.stringify({ iv: ivB64, value, mac, tag: '' })).toString('base64');
}

