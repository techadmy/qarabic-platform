import { Injectable } from '@nestjs/common';
import type { SeriesChangeDto, updateSessionSchema } from '@qarabic/shared';
import type { z } from 'zod';
import type { AuthUser } from '../auth/auth.types.js';
import { validationError } from '../common/errors.js';
import { PrismaService } from '../prisma/prisma.service.js';
import { ConflictChecker } from '../schedule/conflicts.js';
import { EnrollmentsService } from '../schedule/enrollments.service.js';
import { addDays, dateMs, DAY, fromDbDate, isoWeekday, local, maxDate } from '../schedule/time.js';
import { SettingsService } from '../settings/settings.service.js';
import { Actor } from './state-machine.js';
import { SessionsService } from './sessions.service.js';

type Patch = z.output<typeof updateSessionSchema>;

/**
 * D148 (docs/42 §3.4) "this and following": the class moves on its own (detached, its history
 * kept) and its weekly slot gets a new version from the day after, with the new weekday, time,
 * duration and teacher. Both are checked first (one 409 / warnings answer for the pair), so a
 * refused change writes nothing. Later untouched classes are re-generated by the re-sync.
 */
@Injectable()
export class SeriesEditService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly settings: SettingsService,
    private readonly checker: ConflictChecker,
    private readonly sessions: SessionsService,
    private readonly enrollments: EnrollmentsService,
  ) {}

  async following(id: number, body: Patch, viewer: AuthUser): Promise<SeriesChangeDto> {
    const s = await this.prisma.classSession.findUniqueOrThrow({
      where: { id },
      include: { slot: true, enrollment: true },
    });
    if (!s.slot || !s.occurrenceDate || !s.enrollment || s.isDetached) {
      throw validationError({
        scope: ['Only a class that still follows its weekly time can move the following ones.'],
      });
    }
    const slot = s.slot;
    const startsAt = body.startsAt ? Date.parse(body.startsAt) : s.startsAt.getTime();
    const minutes = body.durationMinutes ?? s.durationMinutes;
    const teacherId = body.teacherId ?? s.teacherId;
    const occurrence = fromDbDate(s.occurrenceDate);
    // The new weekly time, read in the slot's own zone (the family's clock).
    const moved = local(startsAt, slot.timezone);
    if (Math.abs(dateMs(moved.date) - dateMs(occurrence)) >= 7 * DAY) {
      throw validationError({
        startsAt: ['Move the following classes within the same week; use the enrollment for more.'],
      });
    }
    // The new version starts after both the old and the new day of this week: this week's class is
    // the moved one, so the generator neither duplicates nor drops it.
    const effectiveFrom = addDays(maxDate(occurrence, moved.date), 1);

    const st = await this.settings.all();
    const check = await this.checker.checkSession(
      this.prisma,
      {
        teacherId,
        studentId: s.studentId,
        startsAt,
        durationMinutes: minutes,
        enrollmentId: s.enrollment.id,
        excludeSessionId: s.id,
      },
      st,
    );
    check.merge(
      await this.checker.checkSlot(
        this.prisma,
        {
          teacherId,
          studentId: s.studentId,
          weekday: isoWeekday(moved.date),
          localStartTime: moved.time,
          durationMinutes: minutes,
          timezone: slot.timezone,
          validFrom: effectiveFrom,
          validTo: slot.validTo ? fromDbDate(slot.validTo) : null,
          enrollmentId: s.enrollment.id,
          excludeSlotIds: [slot.id],
        },
        st,
      ),
    );
    check.assertPasses(body.acknowledgeWarnings);

    // 1) This class (lockVersion / expectedStage guard, its own history).
    await this.sessions.reschedule(
      id,
      { ...body, startsAt: new Date(startsAt).toISOString(), durationMinutes: minutes, teacherId },
      await Actor.of(this.prisma, viewer),
      body.acknowledgeWarnings,
    );
    // 2) The weekly slot from the day after.
    const { slotId } = await this.enrollments.versionSlot(
      slot.id,
      {
        weekday: isoWeekday(moved.date),
        localStartTime: moved.time,
        durationMinutes: minutes,
        effectiveFrom,
        acknowledgeWarnings: body.acknowledgeWarnings,
        teacherId,
      },
      viewer,
    );
    const later = await this.prisma.classSession.findMany({
      where: { scheduleSlotId: slotId, deletedAt: null },
      select: { id: true },
      orderBy: { startsAt: 'asc' },
    });
    return {
      closedSlotId: slot.id,
      newSlotId: slotId,
      effectiveFrom,
      movedSessionIds: later.map((x) => x.id),
    };
  }
}
